-- V1: identity, roles, profiles, skills, and refresh-token storage.
-- Kept in one migration because these tables share the user identity key.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(100),
    google_sub VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_logins INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_google_sub UNIQUE (google_sub),
    CONSTRAINT ck_users_failed_logins_nonnegative CHECK (failed_logins >= 0)
);

CREATE TABLE user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_type VARCHAR(20) NOT NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_user_roles_user_role UNIQUE (user_id, role_type),
    CONSTRAINT ck_user_roles_role_type CHECK (role_type IN ('EMPLOYEE', 'TECHNICIAN', 'ADMINISTRATOR'))
);

CREATE TABLE employee_profiles (
    user_id BIGINT PRIMARY KEY,
    department VARCHAR(80),
    location VARCHAR(80),
    CONSTRAINT fk_employee_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE technician_profiles (
    user_id BIGINT PRIMARY KEY,
    experience_level SMALLINT NOT NULL,
    escalation_level SMALLINT NOT NULL,
    availability VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE',
    max_load INTEGER NOT NULL DEFAULT 10,
    last_assigned_at TIMESTAMPTZ,
    CONSTRAINT fk_technician_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_technician_profiles_experience CHECK (experience_level BETWEEN 1 AND 5),
    CONSTRAINT ck_technician_profiles_escalation CHECK (escalation_level BETWEEN 0 AND 1),
    CONSTRAINT ck_technician_profiles_availability CHECK (availability IN ('AVAILABLE', 'BUSY', 'AWAY', 'OFF_DUTY')),
    CONSTRAINT ck_technician_profiles_max_load CHECK (max_load BETWEEN 1 AND 50)
);

CREATE TABLE administrator_profiles (
    user_id BIGINT PRIMARY KEY,
    scope VARCHAR(20) NOT NULL,
    CONSTRAINT fk_administrator_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_administrator_profiles_scope CHECK (scope IN ('SYSTEM_ADMIN', 'IT_MANAGER'))
);

CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    CONSTRAINT uk_skills_name UNIQUE (name)
);

CREATE TABLE technician_skills (
    technician_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    proficiency SMALLINT NOT NULL,
    CONSTRAINT pk_technician_skills PRIMARY KEY (technician_id, skill_id),
    CONSTRAINT fk_technician_skills_technician FOREIGN KEY (technician_id) REFERENCES technician_profiles (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_technician_skills_skill FOREIGN KEY (skill_id) REFERENCES skills (id),
    CONSTRAINT ck_technician_skills_proficiency CHECK (proficiency BETWEEN 1 AND 5)
);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(100) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_refresh_tokens_token_hash ON refresh_tokens (token_hash);

