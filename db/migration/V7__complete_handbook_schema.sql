-- Additive correction: V1-V6 have already run in CI; preserve their checksums.
CREATE TABLE problem_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200),
    service_id BIGINT REFERENCES services(id),
    status VARCHAR(10) CHECK (status IN ('OPEN', 'RESOLVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE incidents ADD CONSTRAINT fk_incidents_problem
    FOREIGN KEY (problem_id) REFERENCES problem_records(id);

CREATE TABLE incident_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    filename VARCHAR(200),
    content_type VARCHAR(80),
    size_bytes BIGINT CHECK (size_bytes >= 0),
    storage_path VARCHAR(300),
    uploaded_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE incident_embeddings (
    incident_id BIGINT PRIMARY KEY REFERENCES incidents(id),
    vector DOUBLE PRECISION[] NOT NULL,
    model VARCHAR(60),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION reject_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit_records is append-only' USING ERRCODE = '55000';
END;
$$;
CREATE TRIGGER audit_records_no_update_delete
    BEFORE UPDATE OR DELETE ON audit_records
    FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();
CREATE TRIGGER audit_records_no_truncate
    BEFORE TRUNCATE ON audit_records
    FOR EACH STATEMENT EXECUTE FUNCTION reject_audit_mutation();

