-- V10: password reset and two-step verification (A12), simulated mobile push (A4).
-- Additive: no earlier migration is edited.

-- Two-step verification (TOTP) state of a user. The secret is cleared when it is turned off.
ALTER TABLE users
    ADD COLUMN totp_secret VARCHAR(64),
    ADD COLUMN totp_enabled BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN totp_last_step BIGINT;

-- Password reset links. Only the SHA-256 hash of the secret is stored; a link works once.
CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_password_reset_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens (user_id);

-- Devices registered for push notifications. The token is the push provider's address of one device.
CREATE TABLE push_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    token VARCHAR(255) NOT NULL,
    platform VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_push_devices_token UNIQUE (token),
    CONSTRAINT ck_push_devices_platform CHECK (platform IN ('WEB', 'ANDROID', 'IOS'))
);
CREATE INDEX idx_push_devices_user ON push_devices (user_id);

-- New audit actions.
ALTER TABLE audit_records DROP CONSTRAINT ck_audit_records_action;
ALTER TABLE audit_records ADD CONSTRAINT ck_audit_records_action
    CHECK (action IN ('INCIDENT_CREATED', 'CLASSIFIED', 'PRIORITY_CALCULATED', 'PRIORITY_CHANGED', 'ASSIGNED', 'REASSIGNED', 'ACKNOWLEDGED', 'WORK_STARTED', 'INFO_REQUESTED', 'INFO_PROVIDED', 'RESOLVED', 'VERIFIED', 'CLOSED', 'REOPENED', 'ESCALATED', 'COMMENT_ADDED', 'SLA_WARNING', 'SLA_VIOLATED', 'DUPLICATE_LINKED', 'LOGIN_FAILED', 'ACCESS_DENIED', 'USER_ROLE_CHANGED', 'CONFIG_CHANGED', 'ATTACHMENT_ADDED', 'PASSWORD_RESET_REQUESTED', 'PASSWORD_CHANGED', 'MFA_ENABLED', 'MFA_DISABLED'));

-- A simulated push is stored like a simulated text message, so GET /notifications?channel=PUSH_SIM lists it.
ALTER TABLE notifications DROP CONSTRAINT ck_notifications_channel;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_channel
    CHECK (channel IN ('IN_APP', 'EMAIL', 'WEBSOCKET', 'SMS_SIM', 'PUSH_SIM'));
