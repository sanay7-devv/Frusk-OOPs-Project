-- V2: service/category catalog, SLA policy, escalation policy, and live settings.
CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    owner VARCHAR(80),
    criticality SMALLINT NOT NULL,
    always_p1 BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_services_name UNIQUE (name),
    CONSTRAINT ck_services_criticality CHECK (criticality BETWEEN 1 AND 5)
);

CREATE TABLE service_dependencies (
    service_id BIGINT NOT NULL,
    depends_on_id BIGINT NOT NULL,
    CONSTRAINT pk_service_dependencies PRIMARY KEY (service_id, depends_on_id),
    CONSTRAINT fk_service_dependencies_service FOREIGN KEY (service_id) REFERENCES services (id) ON DELETE CASCADE,
    CONSTRAINT fk_service_dependencies_depends_on FOREIGN KEY (depends_on_id) REFERENCES services (id),
    CONSTRAINT ck_service_dependencies_not_self CHECK (service_id <> depends_on_id)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    parent_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id)
);

CREATE TABLE category_skills (
    category_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    CONSTRAINT pk_category_skills PRIMARY KEY (category_id, skill_id),
    CONSTRAINT fk_category_skills_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE,
    CONSTRAINT fk_category_skills_skill FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE sla_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT,
    priority CHAR(2) NOT NULL,
    response_minutes INTEGER NOT NULL,
    resolution_minutes INTEGER NOT NULL,
    calendar_type VARCHAR(12) NOT NULL DEFAULT 'ALWAYS',
    CONSTRAINT fk_sla_policies_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT uk_sla_policies_service_priority UNIQUE (service_id, priority),
    CONSTRAINT ck_sla_policies_priority CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_sla_policies_resolution_after_response CHECK (resolution_minutes > response_minutes),
    CONSTRAINT ck_sla_policies_response_minutes CHECK (response_minutes BETWEEN 1 AND 10080),
    CONSTRAINT ck_sla_policies_resolution_minutes CHECK (resolution_minutes BETWEEN 1 AND 43200),
    CONSTRAINT ck_sla_policies_calendar_type CHECK (calendar_type IN ('ALWAYS', 'BUSINESS_HRS'))
);

CREATE TABLE escalation_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority CHAR(2) NOT NULL,
    level SMALLINT NOT NULL,
    timeout_minutes INTEGER NOT NULL,
    CONSTRAINT uk_escalation_policies_priority_level UNIQUE (priority, level),
    CONSTRAINT ck_escalation_policies_priority CHECK (priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_escalation_policies_level CHECK (level BETWEEN 1 AND 3),
    CONSTRAINT ck_escalation_policies_timeout CHECK (timeout_minutes > 0)
);

CREATE TABLE app_config (
    key VARCHAR(80) PRIMARY KEY,
    value VARCHAR(200) NOT NULL,
    description VARCHAR(200)
);
