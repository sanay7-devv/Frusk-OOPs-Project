-- V3: incident aggregate, lifecycle/SLA state, and comments.
CREATE SEQUENCE incident_code_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    reporter_id BIGINT NOT NULL,
    category_id BIGINT,
    service_id BIGINT NOT NULL,
    assignee_id BIGINT,
    impact SMALLINT NOT NULL,
    urgency SMALLINT NOT NULL,
    affected_users INTEGER NOT NULL,
    priority_score INTEGER,
    priority CHAR(2),
    priority_breakdown JSONB,
    status VARCHAR(20) NOT NULL,
    closure_reason VARCHAR(15),
    major BOOLEAN NOT NULL DEFAULT FALSE,
    escalation_level SMALLINT NOT NULL DEFAULT 0,
    problem_id BIGINT,
    duplicate_of_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ,
    acknowledged_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    response_due TIMESTAMPTZ,
    resolution_due TIMESTAMPTZ,
    paused_at TIMESTAMPTZ,
    paused_seconds BIGINT NOT NULL DEFAULT 0,
    resp_violated BOOLEAN NOT NULL DEFAULT FALSE,
    res_violated BOOLEAN NOT NULL DEFAULT FALSE,
    resp_warn75_sent BOOLEAN NOT NULL DEFAULT FALSE,
    resp_warn90_sent BOOLEAN NOT NULL DEFAULT FALSE,
    res_warn75_sent BOOLEAN NOT NULL DEFAULT FALSE,
    res_warn90_sent BOOLEAN NOT NULL DEFAULT FALSE,
    reopen_count INTEGER NOT NULL DEFAULT 0,
    root_cause TEXT,
    resolution_notes TEXT,
    resolution_steps TEXT,
    time_spent_minutes INTEGER,
    reusable_solution BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_incidents_code UNIQUE (code),
    CONSTRAINT fk_incidents_reporter FOREIGN KEY (reporter_id) REFERENCES users (id),
    CONSTRAINT fk_incidents_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_incidents_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT fk_incidents_assignee FOREIGN KEY (assignee_id) REFERENCES users (id),
    CONSTRAINT fk_incidents_duplicate_of FOREIGN KEY (duplicate_of_id) REFERENCES incidents (id),
    CONSTRAINT ck_incidents_impact CHECK (impact BETWEEN 1 AND 5),
    CONSTRAINT ck_incidents_urgency CHECK (urgency BETWEEN 1 AND 5),
    CONSTRAINT ck_incidents_affected_users CHECK (affected_users >= 1),
    CONSTRAINT ck_incidents_escalation_level CHECK (escalation_level BETWEEN 0 AND 3),
    CONSTRAINT ck_incidents_priority CHECK (priority IS NULL OR priority IN ('P1', 'P2', 'P3', 'P4')),
    CONSTRAINT ck_incidents_status CHECK (status IN ('NEW', 'CLASSIFIED', 'ASSIGNED', 'ACKNOWLEDGED', 'IN_PROGRESS', 'PENDING_USER_INFO', 'RESOLVED', 'VERIFIED', 'CLOSED', 'REOPENED')),
    CONSTRAINT ck_incidents_closure_reason CHECK (closure_reason IS NULL OR closure_reason IN ('VERIFIED', 'AUTO_VERIFIED', 'DUPLICATE', 'WITHDRAWN')),
    CONSTRAINT ck_incidents_paused_seconds CHECK (paused_seconds >= 0),
    CONSTRAINT ck_incidents_reopen_count CHECK (reopen_count >= 0),
    CONSTRAINT ck_incidents_time_spent CHECK (time_spent_minutes IS NULL OR time_spent_minutes >= 0)
);

CREATE INDEX idx_incidents_status ON incidents (status);
CREATE INDEX idx_incidents_priority ON incidents (priority);
CREATE INDEX idx_incidents_service ON incidents (service_id);
CREATE INDEX idx_incidents_assignee ON incidents (assignee_id);
CREATE INDEX idx_incidents_reporter ON incidents (reporter_id);
CREATE INDEX idx_incidents_created_at ON incidents (created_at);
CREATE INDEX idx_incidents_category ON incidents (category_id);
CREATE INDEX idx_incidents_response_due ON incidents (response_due);
CREATE INDEX idx_incidents_resolution_due ON incidents (resolution_due);

CREATE TABLE incident_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    visibility VARCHAR(10) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_incident_comments_incident FOREIGN KEY (incident_id) REFERENCES incidents (id) ON DELETE CASCADE,
    CONSTRAINT fk_incident_comments_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT ck_incident_comments_visibility CHECK (visibility IN ('PUBLIC', 'INTERNAL'))
);

CREATE INDEX idx_incident_comments_incident ON incident_comments (incident_id);

