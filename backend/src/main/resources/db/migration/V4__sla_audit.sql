-- V4: SLA breach records and append-only audit history.
CREATE TABLE sla_violations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL,
    type VARCHAR(10) NOT NULL,
    overdue_seconds BIGINT NOT NULL,
    technician_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sla_violations_incident FOREIGN KEY (incident_id) REFERENCES incidents (id),
    CONSTRAINT fk_sla_violations_technician FOREIGN KEY (technician_id) REFERENCES users (id),
    CONSTRAINT ck_sla_violations_type CHECK (type IN ('RESPONSE', 'RESOLUTION')),
    CONSTRAINT ck_sla_violations_overdue CHECK (overdue_seconds >= 0)
);
CREATE INDEX idx_sla_violations_incident ON sla_violations (incident_id);
CREATE INDEX idx_sla_violations_created_at ON sla_violations (created_at);

CREATE TABLE audit_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT,
    actor_id BIGINT,
    action VARCHAR(40) NOT NULL,
    previous_state VARCHAR(20),
    new_state VARCHAR(20),
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_records_incident FOREIGN KEY (incident_id) REFERENCES incidents (id),
    CONSTRAINT fk_audit_records_actor FOREIGN KEY (actor_id) REFERENCES users (id),
    CONSTRAINT ck_audit_records_action CHECK (action IN ('INCIDENT_CREATED', 'CLASSIFIED', 'PRIORITY_CALCULATED', 'PRIORITY_CHANGED', 'ASSIGNED', 'REASSIGNED', 'ACKNOWLEDGED', 'WORK_STARTED', 'INFO_REQUESTED', 'INFO_PROVIDED', 'RESOLVED', 'VERIFIED', 'CLOSED', 'REOPENED', 'ESCALATED', 'COMMENT_ADDED', 'SLA_WARNING', 'SLA_VIOLATED', 'DUPLICATE_LINKED', 'LOGIN_FAILED', 'ACCESS_DENIED', 'USER_ROLE_CHANGED', 'CONFIG_CHANGED')),
    CONSTRAINT ck_audit_records_previous_state CHECK (previous_state IS NULL OR previous_state IN ('NEW', 'CLASSIFIED', 'ASSIGNED', 'ACKNOWLEDGED', 'IN_PROGRESS', 'PENDING_USER_INFO', 'RESOLVED', 'VERIFIED', 'CLOSED', 'REOPENED')),
    CONSTRAINT ck_audit_records_new_state CHECK (new_state IS NULL OR new_state IN ('NEW', 'CLASSIFIED', 'ASSIGNED', 'ACKNOWLEDGED', 'IN_PROGRESS', 'PENDING_USER_INFO', 'RESOLVED', 'VERIFIED', 'CLOSED', 'REOPENED'))
);
CREATE INDEX idx_audit_records_incident_created ON audit_records (incident_id, created_at);
CREATE INDEX idx_audit_records_actor ON audit_records (actor_id);

