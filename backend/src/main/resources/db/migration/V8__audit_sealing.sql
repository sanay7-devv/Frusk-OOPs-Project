-- Audit sealing entities arrived in main after the initial test branch.
-- Preserve V1-V7 checksums and add the tables expected by Hibernate.
CREATE TABLE audit_seals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_id BIGINT NOT NULL,
    to_id BIGINT NOT NULL,
    record_count INTEGER NOT NULL CHECK (record_count > 0),
    hash VARCHAR(64) NOT NULL,
    prev_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CHECK (from_id <= to_id)
);
CREATE TABLE audit_seal_entries (
    record_id BIGINT PRIMARY KEY REFERENCES audit_records(id),
    seal_id BIGINT NOT NULL REFERENCES audit_seals(id),
    digest VARCHAR(64) NOT NULL
);
CREATE INDEX idx_audit_seal_entries_seal ON audit_seal_entries(seal_id);

CREATE TRIGGER audit_seals_no_update_delete BEFORE UPDATE OR DELETE ON audit_seals
    FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();
CREATE TRIGGER audit_seals_no_truncate BEFORE TRUNCATE ON audit_seals
    FOR EACH STATEMENT EXECUTE FUNCTION reject_audit_mutation();
CREATE TRIGGER audit_seal_entries_no_update_delete BEFORE UPDATE OR DELETE ON audit_seal_entries
    FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();
CREATE TRIGGER audit_seal_entries_no_truncate BEFORE TRUNCATE ON audit_seal_entries
    FOR EACH STATEMENT EXECUTE FUNCTION reject_audit_mutation();
